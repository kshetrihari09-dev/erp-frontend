// Recording test double for '@/services/api' (date-range popup tests): every API method call is captured
// as { api, method, args } and answered with an empty paginated success response.
export const calls: { api: string; method: string; args: any[] }[] = []
const page = (data: any = []) => ({ data: { success: true, data, pagination: { total: 0, page: 1, limit: 20 }, summary: {} } })
const rec = (api: string): any => new Proxy({}, { get: (_t, method: string) => (...args: any[]) => { calls.push({ api, method, args }); return Promise.resolve(page()) } })
export const paramsOf = (method: string) => calls.filter(c => c.method === method).map(c => c.args[0] ?? {})
